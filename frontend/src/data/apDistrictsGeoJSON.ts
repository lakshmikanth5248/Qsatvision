export function generateAPGeoJSONFeatureCollection() {
  const features = AP_DISTRICTS.map((d) => {
    const [lat, lng] = d.center;
    const rLat = 0.28 + (d.areaSqKm / 35000);
    const rLng = 0.35 + (d.areaSqKm / 30000);
    
    const coordinates = [
      [lng - rLng * 0.8, lat + rLat * 0.9],
      [lng + rLng * 0.3, lat + rLat * 1.1],
      [lng + rLng * 1.0, lat + rLat * 0.4],
      [lng + rLng * 0.9, lat - rLat * 0.6],
      [lng + rLng * 0.2, lat - rLat * 1.0],
      [lng - rLng * 0.7, lat - rLat * 0.8],
      [lng - rLng * 1.1, lat - rLat * 0.1],
      [lng - rLng * 0.8, lat + rLat * 0.9],
    ];

    return {
      type: 'Feature',
      id: d.id,
      properties: {
        id: d.id,
        name: d.name,
        code: d.code,
        hq: d.hq,
        region: d.region,
        areaSqKm: d.areaSqKm,
        population: d.population,
        ndvi: d.baselineMetrics.ndvi,
        ndwi: d.baselineMetrics.ndwi,
        ndbi: d.baselineMetrics.ndbi,
      },
      geometry: {
        type: 'Polygon',
        coordinates: [coordinates]
      }
    };
  });

  return {
    type: 'FeatureCollection',
    features
  };
}
